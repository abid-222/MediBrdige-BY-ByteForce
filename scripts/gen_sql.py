"""Regenerates supabase/migrations/0002_core.sql from the SQLAlchemy models so SQL and ORM never drift.
Usage: cd apps/api && python ../../scripts/gen_sql.py"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "apps", "api"))
from sqlalchemy.dialects import postgresql
from sqlalchemy.schema import CreateIndex, CreateTable
from app import models  # noqa
from app.core.db import Base

out = ["-- GENERATED by scripts/gen_sql.py from apps/api/app/models.py. Do not hand-edit; re-run the script.",
       "-- Ids are varchar(36) UUID strings so the same models run on SQLite (dev/tests) and Postgres/Supabase.", ""]
for t in Base.metadata.sorted_tables:
    out.append(str(CreateTable(t).compile(dialect=postgresql.dialect())).strip() + ";")
    for ix in t.indexes:
        out.append(str(CreateIndex(ix).compile(dialect=postgresql.dialect())).strip() + ";")
    out.append("")
path = os.path.join(os.path.dirname(__file__), "..", "supabase", "migrations", "0002_core.sql")
open(path, "w").write("\n".join(out))
print("tables:", len(Base.metadata.sorted_tables))
